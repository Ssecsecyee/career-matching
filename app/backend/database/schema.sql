-- MySQL 8.0+: empty schema only. Select an existing database before execution.
-- No INSERT, DROP, DELETE, or TRUNCATE statements.
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS job_postings (
  job_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  source VARCHAR(40) NOT NULL,
  source_id VARCHAR(128) NOT NULL,
  source_url TEXT NOT NULL,
  title TEXT NOT NULL,
  company_name VARCHAR(255) NOT NULL,
  company_url TEXT NULL,
  service_info LONGTEXT NULL,
  responsibilities LONGTEXT NULL,
  qualifications LONGTEXT NULL,
  preferred_requirements LONGTEXT NULL,
  benefits LONGTEXT NULL,
  hiring_process LONGTEXT NULL,
  application_notes LONGTEXT NULL,
  tech_stacks JSON NULL,
  original_categories JSON NULL,
  role_categories JSON NULL,
  addresses JSON NULL,
  location_text TEXT NULL,
  education_text TEXT NULL,
  education_source JSON NULL,
  career_source JSON NULL,
  min_career_years DECIMAL(5,2) NULL,
  max_career_years DECIMAL(5,2) NULL,
  newcomer BOOLEAN NULL,
  employment_type VARCHAR(80) NULL,
  work_mode VARCHAR(80) NULL,
  published_at DATETIME(6) NULL,
  deadline_at DATETIME(6) NULL,
  deadline_type VARCHAR(40) NOT NULL DEFAULT 'unknown',
  recruitment_status VARCHAR(40) NOT NULL DEFAULT 'unknown',
  field_status JSON NULL,
  additional_sections JSON NULL,
  raw_detail JSON NULL,
  raw_object_key TEXT NULL,
  content_hash CHAR(64) NULL,
  source_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  source_updated_at DATETIME(6) NULL,
  fetched_at DATETIME(6) NOT NULL,
  last_seen_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (job_id),
  UNIQUE KEY uq_job_source (source, source_id),
  KEY ix_job_status_deadline (recruitment_status, deadline_at),
  KEY ix_job_updated (updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS job_requirements (
  requirement_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  job_id BIGINT UNSIGNED NOT NULL,
  requirement_type VARCHAR(24) NOT NULL COMMENT 'required/preferred/unspecified',
  condition_type VARCHAR(40) NOT NULL COMMENT 'skill/education/experience/certificate/other',
  original_text LONGTEXT NOT NULL,
  normalized_condition JSON NULL,
  logic_expression JSON NULL COMMENT 'Preserve nested AND/OR; never flatten to all required',
  evidence_section VARCHAR(128) NOT NULL,
  evidence_quote LONGTEXT NOT NULL,
  source_version BIGINT UNSIGNED NOT NULL,
  sort_order INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (requirement_id),
  KEY ix_requirement_job (job_id, requirement_type),
  CONSTRAINT fk_requirement_job FOREIGN KEY (job_id) REFERENCES job_postings(job_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

