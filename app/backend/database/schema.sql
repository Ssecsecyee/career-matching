-- Application-owned records. All DATETIME values use UTC by convention.
-- Retention intervals must be configured before production use.
CREATE TABLE IF NOT EXISTS chat_sessions (
  session_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  owner_scope VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  stage VARCHAR(40) NOT NULL DEFAULT 'initial',
  selected_job_ids JSON NULL,
  profile_snapshot JSON NULL,
  profile_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  requirement_answers JSON NULL,
  state_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  cumulative_input_tokens BIGINT UNSIGNED NOT NULL DEFAULT 0,
  cumulative_output_tokens BIGINT UNSIGNED NOT NULL DEFAULT 0,
  model_call_count INT UNSIGNED NOT NULL DEFAULT 0,
  expires_at DATETIME(6) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (session_id),
  KEY ix_session_owner (owner_scope, updated_at),
  KEY ix_session_expiry (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS chat_messages (
  message_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  session_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  sequence_no BIGINT UNSIGNED NOT NULL,
  idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  role VARCHAR(24) NOT NULL COMMENT 'user/assistant',
  content LONGTEXT NOT NULL,
  structured_content JSON NULL,
  stage VARCHAR(40) NOT NULL,
  source_version_snapshot JSON NULL,
  expires_at DATETIME(6) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (message_id),
  UNIQUE KEY uq_message_sequence (session_id, sequence_no),
  UNIQUE KEY uq_message_retry (session_id, idempotency_key, role),
  KEY ix_message_expiry (expires_at),
  CONSTRAINT fk_message_session FOREIGN KEY (session_id) REFERENCES chat_sessions(session_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS model_invocations (
  invocation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  session_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  attempt_no INT UNSIGNED NOT NULL DEFAULT 1,
  purpose VARCHAR(40) NOT NULL,
  provider VARCHAR(40) NOT NULL DEFAULT 'bedrock',
  model_id VARCHAR(255) NOT NULL,
  region VARCHAR(40) NOT NULL,
  prompt_version VARCHAR(80) NOT NULL,
  policy_version VARCHAR(80) NOT NULL,
  input_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  source_version_snapshot JSON NULL,
  status VARCHAR(40) NOT NULL COMMENT 'pending/succeeded/failed/timed_out',
  input_tokens BIGINT UNSIGNED NULL,
  output_tokens BIGINT UNSIGNED NULL,
  cache_read_input_tokens BIGINT UNSIGNED NULL,
  cache_write_input_tokens BIGINT UNSIGNED NULL,
  latency_ms BIGINT UNSIGNED NULL,
  estimated_cost DECIMAL(18,8) NULL,
  cost_currency CHAR(3) NULL,
  pricing_version VARCHAR(80) NULL,
  provider_request_id VARCHAR(255) NULL,
  error_code VARCHAR(128) NULL,
  started_at DATETIME(6) NOT NULL,
  finished_at DATETIME(6) NULL,
  expires_at DATETIME(6) NOT NULL,
  PRIMARY KEY (invocation_id),
  UNIQUE KEY uq_invocation_attempt (session_id, request_id, purpose, attempt_no),
  KEY ix_invocation_expiry (expires_at),
  KEY ix_invocation_started (started_at),
  CONSTRAINT fk_invocation_session FOREIGN KEY (session_id) REFERENCES chat_sessions(session_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS recommendation_evidence (
  evidence_record_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  message_id BIGINT UNSIGNED NOT NULL,
  subject_type VARCHAR(24) NOT NULL COMMENT 'job/program',
  subject_id BIGINT UNSIGNED NOT NULL,
  source_version BIGINT UNSIGNED NOT NULL,
  source_url TEXT NOT NULL,
  requirement_id BIGINT UNSIGNED NULL COMMENT 'Optional reference; original snapshot remains authoritative',
  requirement_type VARCHAR(24) NULL,
  requirement_snapshot JSON NULL,
  source_section VARCHAR(128) NOT NULL,
  evidence_quote LONGTEXT NOT NULL,
  user_fact_snapshot JSON NULL,
  assessment_status VARCHAR(24) NOT NULL COMMENT 'met/unmet/unknown/not_applicable',
  explanation LONGTEXT NOT NULL COMMENT 'User-facing evidence-based explanation; no hidden reasoning trace',
  validation_status VARCHAR(24) NOT NULL DEFAULT 'pending',
  rule_version VARCHAR(80) NOT NULL,
  expires_at DATETIME(6) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (evidence_record_id),
  KEY ix_evidence_message (message_id),
  KEY ix_evidence_subject (subject_type, subject_id, source_version),
  KEY ix_evidence_expiry (expires_at),
  CONSTRAINT fk_evidence_message FOREIGN KEY (message_id) REFERENCES chat_messages(message_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS response_cache (
  cache_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  scope_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  cache_kind VARCHAR(24) NOT NULL COMMENT 'search/response',
  cache_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  session_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  session_state_version BIGINT UNSIGNED NULL,
  profile_version BIGINT UNSIGNED NULL,
  stage VARCHAR(40) NULL,
  model_id VARCHAR(255) NULL,
  prompt_version VARCHAR(80) NULL,
  policy_version VARCHAR(80) NOT NULL,
  data_generation BIGINT UNSIGNED NOT NULL,
  dependency_versions JSON NOT NULL,
  payload JSON NOT NULL,
  invalidated_at DATETIME(6) NULL,
  expires_at DATETIME(6) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (cache_id),
  UNIQUE KEY uq_cache_scope (scope_key, cache_kind, cache_key),
  KEY ix_cache_expiry (expires_at),
  KEY ix_cache_generation (data_generation),
  KEY ix_cache_session (session_id),
  CONSTRAINT fk_cache_session FOREIGN KEY (session_id) REFERENCES chat_sessions(session_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;



-- Administrative audit. Provision a separate admin account before exposing admin routes.
CREATE TABLE IF NOT EXISTS admin_audit (
 audit_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 request_id CHAR(36) NOT NULL,
 actor_scope CHAR(64) NOT NULL,
 fingerprint CHAR(64) NOT NULL,
 action VARCHAR(40) NOT NULL,
 entity_id BIGINT UNSIGNED NOT NULL,
 reason VARCHAR(500) NOT NULL,
 before_value JSON NOT NULL,
 after_value JSON NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY uq_admin_request(request_id),
 KEY ix_admin_entity(entity_id,audit_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
